#!/usr/bin/env python3
"""Synth model badges (L2, 2 bits a pixel) in the style of the CHIP badges.

Takes the CHIP pills as templates, fills their lettering and cuts NAME from a 5x7 block font.
Usage: gen_synth_badge.py NAME  ->  <name>_mini_nomark_80x28_L2.h and <name>_med_108x40_L2.h
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

FONT = {
    "A": ["01110", "10001", "10001", "11111", "10001", "10001", "10001"],
    "E": ["11111", "10000", "10000", "11110", "10000", "10000", "11111"],
    "G": ["01111", "10000", "10000", "10011", "10001", "10001", "01111"],
    "H": ["10001", "10001", "10001", "11111", "10001", "10001", "10001"],
    "I": ["11111", "00100", "00100", "00100", "00100", "00100", "11111"],
    "L": ["10000", "10000", "10000", "10000", "10000", "10000", "11111"],
    "M": ["10001", "11011", "10101", "10101", "10001", "10001", "10001"],
    "N": ["10001", "11001", "10101", "10011", "10001", "10001", "10001"],
    "O": ["01110", "10001", "10001", "10001", "10001", "10001", "01110"],
    "P": ["11110", "10001", "10001", "11110", "10000", "10000", "10000"],
    "R": ["11110", "10001", "10001", "11110", "10100", "10010", "10001"],
    "S": ["01111", "10000", "10000", "01110", "00001", "00001", "11110"],
    "T": ["11111", "00100", "00100", "00100", "00100", "00100", "00100"],
    "Y": ["10001", "10001", "01010", "00100", "00100", "00100", "00100"],
}


def load(name, w, h):
    text = open(os.path.join(HERE, name)).read()
    data = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", text[text.index("{"):])]
    stride = (w + 3) // 4
    return [[(data[y * stride + x // 4] >> (6 - 2 * (x % 4))) & 3 for x in range(w)] for y in range(h)]


def save(px, w, h, path, symbol):
    stride = (w + 3) // 4
    out = bytearray(stride * h)
    for y in range(h):
        for x in range(w):
            out[y * stride + x // 4] |= px[y][x] << (6 - 2 * (x % 4))
    lines = [f"// Generated by gen_synth_badge.py: L2 bitmap ({w}x{h}) in the CHIP badge style",
             f"const uint8_t {symbol}[{len(out)}] = {{"]
    for i in range(0, len(out), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in out[i:i + 16]) + ",")
    lines.append("};")
    open(path, "w").write("\n".join(lines) + "\n")


def badge(name, template, w, h, left, scale):
    px = load(template, w, h)
    # Fill the old lettering: everything between the pill's edges becomes solid.
    for y in range(h):
        xs = [x for x in range(left, w) if px[y][x]]
        if len(xs) > 4:
            for x in range(xs[0] + 2, xs[-1] - 1):
                px[y][x] = 3
    mid = h // 2
    xs = [x for x in range(left, w) if px[mid][x]]
    cx = (xs[0] + xs[-1]) / 2
    tw = (len(name) * 6 - 1) * scale
    x0 = int(round(cx - tw / 2))
    y0 = int(round(h / 2 - 7 * scale / 2))
    for i, ch in enumerate(name):
        for gy, row in enumerate(FONT[ch]):
            for gx, bit in enumerate(row):
                if bit == "1":
                    for dy in range(scale):
                        for dx in range(scale):
                            px[y0 + gy * scale + dy][x0 + (i * 6 + gx) * scale + dx] = 0
    return px


def main():
    name = sys.argv[1].upper()
    low = name.lower()
    mini = badge(name, "chip_mini_nomark_80x28_L2.h", 80, 28, 0, 2)
    save(mini, 80, 28, os.path.join(HERE, f"{low}_mini_nomark_80x28_L2.h"), f"{low}_mini_nomark_80x28_L2")
    med = badge(name, "chip_med_108x40_L2.h", 108, 40, 0, 3)
    save(med, 108, 40, os.path.join(HERE, f"{low}_med_108x40_L2.h"), f"{low}_med_108x40_L2")


if __name__ == "__main__":
    main()
