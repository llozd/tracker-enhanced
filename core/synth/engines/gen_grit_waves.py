"""GRIT's single-cycle waves (after the MS800): 21 cycles of 256 samples, stored as 8-bit mu-law codes like the
original's companded ROM, and the table that expands a code. The waves are drawn here, not taken from the
instrument (its wave ROM has not been read out): basic shapes, harmonic stacks, formants and noises."""
import math
import random
import sys
from pathlib import Path

N = 256
MU = 255.0


def additive(amps):
    return [sum(a * math.sin(2 * math.pi * (h + 1) * i / N) for h, a in enumerate(amps)) for i in range(N)]


def formant(f1, f2, bw=0.18):
    """harmonics 1..40 under two resonance peaks (in harmonics of the cycle)"""
    def peak(h, f):
        return 1.0 / (1.0 + ((h - f) / (bw * f)) ** 2)
    return additive([(peak(h, f1) + 0.6 * peak(h, f2)) / (h ** 0.3) for h in range(1, 41)])


def waves():
    rnd = random.Random(800)
    ph = [i / N for i in range(N)]
    w = {
        "SINE": [math.sin(2 * math.pi * p) for p in ph],
        "TRI": [1 - 4 * abs(p - 0.5) for p in ph],
        "SAW": [1 - 2 * p for p in ph],
        "SQR": [1.0 if p < 0.5 else -1.0 for p in ph],
        "P25": [1.0 if p < 0.25 else -1.0 for p in ph],
        "P12": [1.0 if p < 0.125 else -1.0 for p in ph],
        "ORGN": additive([1, 0.8, 0.6, 0.5, 0, 0.35, 0, 0.3]),
        "OCTV": additive([1 if h + 1 in (1, 2, 4, 8, 16, 32) else 0 for h in range(32)]),
        "FIFT": additive([1 if h + 1 in (1, 3, 6, 12, 24) else 0 for h in range(24)]),
        "HOLW": additive([1 / (h + 1) if h % 2 == 0 else 0 for h in range(15)]),
        "BUZZ": additive([1.0] * 24),
        "AH": formant(3.5, 6.0),
        "EE": formant(1.5, 11.0),
        "BELL": additive([1 if h + 1 in (1, 5, 9, 13, 17) else 0 for h in range(17)]),
        "SYNC": [1 - 2 * ((p * 2.6) % 1.0) for p in ph],
        "RESO": [(1 - 2 * p) * 0.3 + math.sin(2 * math.pi * 9 * p) * (1 - p) for p in ph],
        "FOLD": [math.sin(2 * math.pi * p + 3.2 * math.sin(2 * math.pi * p)) for p in ph],
        "RHRM": additive([rnd.random() ** 2 for _ in range(32)]),
        "NOIS": [rnd.uniform(-1, 1) for _ in ph],
        "DUST": None,
        "STEP": [((int(p * 8) * 5) % 8) / 3.5 - 1 for p in ph],
    }
    acc, dust = 0.0, []                                  # a smoothed noise: a darker, rumbling cycle
    for _ in range(2 * N):
        acc = 0.85 * acc + rnd.uniform(-1, 1)
        dust.append(acc)
    w["DUST"] = dust[N:]
    for k, v in w.items():
        m = sum(v) / N
        v = [x - m for x in v]
        a = max(abs(x) for x in v) or 1.0
        w[k] = [x / a for x in v]
    return w


def mu_code(x):
    y = math.copysign(math.log1p(MU * abs(x)) / math.log1p(MU), x)
    return max(0, min(255, int(round((y + 1) * 127.5))))


def mu_value(c):
    y = c / 127.5 - 1
    return math.copysign(((1 + MU) ** abs(y) - 1) / MU, y)


def main():
    here = Path(__file__).resolve().parent
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else here / "GritWaves.h"
    w = waves()
    vals = [int(round(mu_value(c) * 32767)) for c in range(256)]
    lines = ["#pragma once",
             "",
             "// Generated by gen_grit_waves.py: GRIT's single-cycle waves as 8-bit mu-law codes and their expansion.",
             "",
             "#include <cstdint>",
             "",
             "namespace polysynth::grit",
             "{",
             f"constexpr int kWaveCount = {len(w)};",
             "constexpr int kWaveLength = 256;",
             "constexpr const char* kWaveNames[kWaveCount] = {" + ", ".join(f'"{k}"' for k in w) + "};",
             "constexpr int16_t kMuLaw[256] = {"]
    lines += ["    " + ", ".join(map(str, vals[i:i + 16])) + "," for i in range(0, 256, 16)]
    lines.append("};")
    lines.append("constexpr uint8_t kWaves[kWaveCount][kWaveLength] = {")
    for k, v in w.items():
        codes = [mu_code(x) for x in v]
        lines.append(f"    {{ // {k}")
        lines += ["        " + ", ".join(map(str, codes[i:i + 32])) + "," for i in range(0, N, 32)]
        lines.append("    },")
    lines.append("};")
    lines.append("} // namespace polysynth::grit")
    out.write_text("\n".join(lines) + "\n")
    print(f"gen_grit_waves: {len(w)} waves -> {out}")


if __name__ == "__main__":
    main()
